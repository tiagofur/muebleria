        end

        def component_definition_id
          @identity['componentDefinitionId']
        end

        def catalog_component_id
          @identity['catalogComponentId']
        end

        def role
          @identity['role']
        end

        def option_role
          @identity['optionRole']
        end

        def aabb_min
